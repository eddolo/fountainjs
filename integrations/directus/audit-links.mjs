import assert from 'node:assert/strict';
import { join } from 'node:path';
import { expect } from '@playwright/test';

export async function auditLinks({ side, api, collection, selectInterface, openItem, report, out }) {
  const stock = side === 'stock';
  await selectInterface(stock ? 'input-rich-text-html' : 'fountain-rich-text-html', { toolbar: ['customLink', 'unlink', 'undo', 'redo'] });
  const original = '<p>Read the handbook</p>';
  const { id } = await api('/items/' + collection, { method: 'POST', body: JSON.stringify({ body: original }) });
  const path = '/items/' + collection + '/' + id;
  const route = '/admin/content/' + collection + '/' + id;
  const first = await openItem(side, route);
  const toolbar = page => page.locator(stock ? '.wysiwyg .toolbar' : '.fountain-directus-toolbar');
  function action(page, name, icon) {
    return stock ? toolbar(page).locator('button:has([data-icon="' + icon + '"])') : toolbar(page).getByRole('button', { name, exact: true });
  }
  const drawer = page => page.locator('.v-drawer');
  const apply = page => stock ? drawer(page).getByRole('button', { name: 'Save Link', exact: true }).click()
    : drawer(page).getByRole('button', { name: 'Apply link' }).click();
  const href = 'https://example.org/handbook';
  report.stage = side + ' link a selected word';
  await first.editor.locator('p').click();
  await first.page.keyboard.press('End');
  await first.page.keyboard.press('Control+Shift+ArrowLeft');
  await action(first.page, 'Link', 'link').click();
  const inputs = drawer(first.page).getByRole('textbox');
  await expect(inputs.nth(1)).toHaveValue('handbook');
  await inputs.nth(0).fill(href);
  await inputs.nth(2).fill('Staff guide');
  await drawer(first.page).screenshot({path:join(out, side + '-link.png')});
  await apply(first.page);
  const anchor = first.editor.locator('a');
  await expect(anchor).toHaveAttribute('href', href);
  await expect(anchor).toHaveAttribute('rel','noopener noreferrer');
  await expect(anchor).toHaveAttribute('target','_blank');
  await expect(anchor).toHaveText('handbook');
  assert.equal((await api(path)).body, original);
  await first.page.keyboard.press('Control+s');
  await expect.poll(async () => (await api(path)).body).toContain(href);
  const created = (await api(path)).body;
  await first.context.close();

  const next = await openItem(side, route);
  report.stage = side + ' edit a reopened link';
  const link = next.editor.locator('a');
  await link.click();
  await action(next.page, 'Link', 'link').click();
  const fields = drawer(next.page).getByRole('textbox');
  await expect(fields.nth(0)).toHaveValue(href);
  await expect(fields.nth(1)).toHaveValue('handbook');
  await fields.nth(0).fill('/guides/updated');
  await fields.nth(1).fill('updated guide');
  await drawer(next.page).getByText('New Tab', {exact:true}).click();
  await apply(next.page);
  await expect(link).toHaveText('updated guide');
  await expect(link).not.toHaveAttribute('target',/.+/);
  await expect(link).not.toHaveAttribute('rel',/.+/);
  await next.page.keyboard.press('Control+s');
  await expect.poll(async () => (await api(path)).body).toContain('/guides/updated');
  const edited = (await api(path)).body;
  await next.context.close();

  const reopened = await openItem(side, route);
  report.stage = side + ' unlink and restore through undo';
  await reopened.editor.locator('a').click();
  await action(reopened.page, 'Unlink', 'link_off').click();
  await expect(reopened.editor.locator('a')).toHaveCount(0);
  await expect(reopened.editor.locator('p')).toHaveText('Read the updated guide');
  await action(reopened.page, 'Undo', 'undo').click();
  await expect(reopened.editor.locator('a')).toHaveAttribute('href','/guides/updated');
  await action(reopened.page, 'Redo', 'redo').click();
  await expect(reopened.editor.locator('a')).toHaveCount(0);
  await reopened.page.keyboard.press('Control+s');
  const removed = '<p>Read the updated guide</p>';
  await expect.poll(async () => (await api(path)).body).toBe(removed);
  await reopened.context.close();
  const formatted = '<p>Check <a target="_blank" rel="noopener noreferrer nofollow" href="/staff" title="Team">the <strong>team</strong> guide</a>.</p>';
  const directory = await api('/items/' + collection, { method:'POST', body:JSON.stringify({body:formatted}) });
  const formattedRoute = '/admin/content/' + collection + '/' + directory.id;
  const formattedPath = '/items/' + collection + '/' + directory.id;
  const rich = await openItem(side, formattedRoute);
  report.stage = side + ' retain nested link formatting and author relationship';
  await rich.editor.locator('a strong').click();
  await action(rich.page, 'Link', 'link').click();
  const properties = drawer(rich.page).getByRole('textbox');
  await expect(properties.nth(1)).toHaveValue('the team guide');
  await properties.nth(1).fill('Discard this change');
  await drawer(rich.page).locator('.close-button').click();
  await expect(rich.editor.locator('a')).toHaveText('the team guide');
  await rich.editor.locator('strong').click();
  await action(rich.page,'Link','link').click();
  await properties.nth(0).fill('/directory');
  await drawer(rich.page).getByText('New Tab', {exact:true}).click();
  await apply(rich.page);
  await expect(rich.editor.locator('a strong')).toHaveText('team');
  await expect(rich.editor.locator('a')).toHaveAttribute('rel', 'nofollow');
  await rich.page.keyboard.press('Control+s');
  const richHTML = '<p>Check <a rel="nofollow" href="/directory" title="Team">the <strong>team</strong> guide</a>.</p>';
  await expect.poll(async () => (await api(formattedPath)).body).toBe(richHTML);
  await rich.context.close();

  const blank = await api('/items/' + collection, {method:'POST', body:JSON.stringify({body:null})});
  const blankPath = '/items/' + collection + '/' + blank.id;
  const empty = await openItem(side, '/admin/content/' + collection + '/' + blank.id);
  report.stage = side + ' insert a link at the empty caret using the keyboard shortcut';
  await empty.editor.click();
  await empty.page.keyboard.press('Control+k');
  const address = 'https://example.org/guide';
  await drawer(empty.page).getByRole('textbox').first().fill(address);
  await apply(empty.page);
  await expect(empty.editor.locator('a')).toHaveText(address);
  await empty.page.keyboard.press('Control+s');
  await expect.poll(async () => (await api(blankPath)).body).toContain(address);
  const insertedAtCaret = (await api(blankPath)).body;
  await empty.context.close();
  let rollback;
  if (!stock) {
    await selectInterface('input-rich-text-html', { toolbar:['customLink'] });
    const restored = await openItem('stock', formattedRoute);
    await expect(restored.editor.locator('a strong')).toHaveText('team');
    await restored.editor.locator('strong').click();
    await restored.page.locator('.wysiwyg .toolbar button:has([data-icon="link"])').click();
    await drawer(restored.page).getByRole('textbox').nth(2).fill('Directory');
    await drawer(restored.page).getByRole('button',{name:'Save Link',exact:true}).click();
    await expect(drawer(restored.page)).toHaveCount(0);
    await expect(restored.editor.locator('a')).toHaveAttribute('title', 'Directory');
    await restored.page.getByRole('button', {name:'Save', exact:true}).click();
    rollback = richHTML.replace('title="Team"', 'title="Directory"');
    await expect.poll(async () => (await api(formattedPath)).body).toBe(rollback);
    await restored.context.close();
  }
  return { id, created, edited, removed, directoryItem: directory.id, richHTML, insertedAtCaret, rollback };
}
