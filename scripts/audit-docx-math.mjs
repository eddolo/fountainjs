// Structural fixture only: these expressions are explicitly authored, not a
// TeX parser. Render the resulting file independently before claiming fidelity.
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { Schema, StarterKit, composeExtensions, createMathExtension } from 'fountainjs-editor';
import { exportDOCX } from 'fountainjs-editor/docx';

const output = resolve(process.argv[2] ?? 'tmp/docx-math-20260907');
const t = (value, style = 'plain') => ({ type: 'text', value, style });
const samples = [
  { source: String.raw`\frac{x^2}{\sqrt{y}}`, expression: { type: 'fraction', numerator: { type: 'script', base: t('x', 'italic'), sup: t('2') }, denominator: { type: 'radical', body: t('y', 'italic') } } },
  { source: String.raw`x_i^2`, expression: { type: 'script', base: t('x', 'italic'), sub: t('i', 'italic'), sup: t('2') } },
  { source: String.raw`\sqrt[3]{x}`, expression: { type: 'radical', degree: t('3'), body: t('x', 'italic') } },
  { source: String.raw`\begin{bmatrix}a&b\\c&d\end{bmatrix}`, expression: { type: 'delimiter', open: '[', close: ']', body: { type: 'matrix', rows: [[t('a'), t('b')], [t('c'), t('d')]] } } },
  { source: String.raw`\sum_{i=0}^n x_i`, expression: { type: 'nary', symbol: '∑', sub: t('i=0'), sup: t('n', 'italic'), limits: 'above-below', body: { type: 'script', base: t('x', 'italic'), sub: t('i', 'italic') } } },
  { source: String.raw`\hat{x}`, expression: { type: 'accent', character: '\u0302', body: t('x', 'italic') } },
];
const schema = new Schema(composeExtensions([...StarterKit.extensions, createMathExtension()]).schema);
const paragraph = value => schema.node('paragraph', {}, [schema.text(value)]);
const nestedMath = () => schema.node('math_block', { latex: samples[0].source });
const doc = schema.node('doc', {}, [
  paragraph('Native Word equation boundary'),
  paragraph('This document tests structured editable equations generated by FountainJS from explicit host math expressions.'),
  schema.node('paragraph', {}, [schema.text('Inline fraction '), schema.node('inline_math', { latex: samples[0].source }), schema.text(' remains inside the sentence.')]),
  ...samples.flatMap((sample, index) => [paragraph(`Example ${index + 1}`), schema.node('math_block', { latex: sample.source })]),
  schema.node('blockquote', {}, [paragraph('Equation inside a quote'), nestedMath()]),
  schema.node('bullet_list', {}, [schema.node('list_item', {}, [paragraph('One list item with an equation and table'), nestedMath(),
    schema.node('table', {}, [schema.node('table_row', {}, [schema.node('table_cell', {}, [paragraph('Equation inside a table cell'), nestedMath()])])]),
  ])]),
]);
const before = JSON.stringify(doc.toJSON());
const result = exportDOCX(doc, {
  title: 'Native Word equation boundary', page: 'letter',
  resolveMath: node => samples.find(sample => sample.source === node.attrs.latex)?.expression,
});
assert.equal(JSON.stringify(doc.toJSON()), before);
assert.equal(result.report.issues.length, 10);
assert(result.report.issues.every(issue => issue.code === 'native-math-experimental'));
await mkdir(output, { recursive: true });
await writeFile(resolve(output, 'native-equations.docx'), result.bytes);
await writeFile(resolve(output, 'expected-source.json'), JSON.stringify(doc.toJSON(), null, 2));
await writeFile(resolve(output, 'report.json'), JSON.stringify(result.report, null, 2));
console.log(`Wrote native-equations.docx and source/report evidence to ${output}. Independent rendering remains required.`);
