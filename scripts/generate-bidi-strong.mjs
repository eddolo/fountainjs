import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const input = new URL('../tests/fixtures/unicode/DerivedBidiClass-17.0.0.txt', import.meta.url);
const output = new URL('../src/core/bidi-strong-data.ts', import.meta.url);
const expectedHash = '4867b4b7f0731ed1bfcd34cc6251211ff1542541fce0734b6fbda139ee80b3a4';
const bytes = await readFile(input);
if (createHash('sha256').update(bytes).digest('hex') !== expectedHash) throw new Error('Unicode source hash mismatch');
const text = bytes.toString('utf8');
// 0 = not L/R/AL, 1 = L, 2 = R/AL. Apply ALL explicit classes after
// @missing defaults: ignoring e.g. AN/NSM/BN would turn them into false L/R.
const values = new Uint8Array(0x110000).fill(1);
const strong = value => ['L', 'Left_To_Right'].includes(value) ? 1
  : ['R', 'AL', 'Right_To_Left', 'Arabic_Letter'].includes(value) ? 2 : 0;
const assign = (start, end, value) => values.fill(strong(value), parseInt(start, 16), parseInt(end ?? start, 16) + 1);
for (const match of text.matchAll(/^# @missing: ([\dA-F]+)(?:\.\.([\dA-F]+))?; (\w+)/gm)) assign(match[1], match[2], match[3]);
for (const match of text.matchAll(/^([\dA-F]+)(?:\.\.([\dA-F]+))?\s*; (\w+)/gm)) assign(match[1], match[2], match[3]);
const entries = [];
for (let point = 0; point < values.length; point += 1) {
  if (point === values.length - 1 || values[point] !== values[point + 1]) entries.push(point, values[point]);
}
const rows = [];
for (let index = 0; index < entries.length; index += 16) rows.push('  ' + entries.slice(index, index + 16).map(value => `0x${value.toString(16)}`).join(', ') + ',');
const source = `// Generated by scripts/generate-bidi-strong.mjs; do not edit by hand.\n// Unicode 17.0.0 DerivedBidiClass: ${expectedHash}\n// Copyright 2025 Unicode, Inc.; Unicode License V3.\n// Full permission notice: THIRD_PARTY_NOTICES.md and tests/fixtures/unicode/LICENSE.txt.\n// Inclusive range ends and strong classes (0 = none, 1 = L, 2 = R/AL).\nexport const bidiStrongRanges: readonly number[] = Object.freeze([\n${rows.join('\n')}\n]);\n`;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== source) throw new Error('Generated Unicode ranges are stale');
} else await writeFile(output, source);
console.log(`Unicode 17.0.0: ${entries.length / 2} disjoint strong-direction ranges; ${Buffer.byteLength(source)} source bytes; ${process.argv.includes('--check') ? 'verified' : 'generated'}.`);
