import { test, expect } from '@playwright/test';
import { fileURLToPath } from 'node:url';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
test.use({ video: 'on' });
for (const kind of ['range', 'quoted', 'nested-list']) test(`edits ${kind} suggestion through focused input, clipboard and saved JSON`, async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const path = fileURLToPath(new URL('./gitlab-suggestion-node.html', import.meta.url)).replaceAll('\\', '/');
  const output = resolve('artifacts/suggestion-node-desktop-20261116', info.project.name, kind); await mkdir(output, { recursive: true });
  await page.goto('/@fs/' + path + '?case=' + kind); await expect(page.getByRole('status')).toHaveText('Ready');
  const editor = page.getByRole('textbox', { name: 'Suggestion editor', exact: true });
  const region = editor.getByRole('region', { name: 'Suggested replacement', exact: true });
  await editor.getByText('Original prose.', { exact: true }).click(); await page.keyboard.press('End');
  const original = kind === 'range' ? 'first();\nsecond();\n' : 'replacement\n';
  const params = kind === 'range' ? '-2+1' : '-0+0';
  await region.focus(); await page.keyboard.type('X');
  await expect.poll(() => region.locator('code').textContent()).toBe('X' + original);
  await page.keyboard.press('Enter'); await page.keyboard.press('Tab');
  await expect.poll(() => region.locator('code').textContent()).toBe('X\n  ' + original);
  await expect(editor.getByText('Original prose.', { exact: true })).toBeVisible();
  await expect(region).toHaveAttribute('data-fountain-gitlab-suggestion', params);
  await editor.focus(); await page.keyboard.press('Control+a'); await page.keyboard.press('Control+c');
  const external = await page.context().newPage(); await external.setContent('<label>External text<textarea aria-label="External text"></textarea></label>');
  await external.getByRole('textbox').focus(); await external.keyboard.press('Control+v');
  const plain = await external.getByRole('textbox').inputValue(); expect(plain).toContain('suggestion:' + params); expect(plain).toContain('X');
  await external.close(); await page.bringToFront();
  await editor.focus(); await page.keyboard.press('Control+a'); await page.keyboard.press('Control+v');
  await expect(region).toHaveCount(1); await expect(region).toHaveAttribute('data-fountain-gitlab-suggestion', params);
  await page.getByRole('button', { name: 'Export Markdown', exact: true }).click();
  const before = await page.getByLabel('Saved Markdown', { exact: true }).inputValue();
  expect(before).toContain('suggestion:' + params); expect(before).toContain('Original prose.');
  await page.getByRole('button', { name: 'Save and reopen JSON', exact: true }).click(); await expect(page.getByRole('status')).toHaveText('Reopened saved JSON');
  await page.getByRole('button', { name: 'Export Markdown', exact: true }).click();
  expect(await page.getByLabel('Saved Markdown', { exact: true }).inputValue()).toBe(before);
  await editor.screenshot({ caret: 'initial', path: resolve(output, 'editor.png') });
  await writeFile(resolve(output, 'source.md'), before); await writeFile(resolve(output, 'external.txt'), plain);
  await writeFile(resolve(output, 'observations.json'), JSON.stringify({ focusEntersSuggestion: true, prosePreserved: true, keyboardEnterTab: true,
    nativeClipboard: true, savedJSONReopened: true, errors }, null, 2));
  expect(errors).toEqual([]);
});
