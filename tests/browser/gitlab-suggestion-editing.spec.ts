import { test, expect } from '@playwright/test';
import { fileURLToPath } from 'node:url';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
test.use({ video: 'on' });
test('edits source and file range through native controls, undo, permission refusal and insertion', async ({ page }, info) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  const path = fileURLToPath(new URL('./gitlab-suggestion-editing.html', import.meta.url)).replaceAll('\\', '/');
  const output = resolve('artifacts/suggestion-editing-desktop-20261116', info.project.name); await mkdir(output, { recursive: true });
  await page.goto('/@fs/' + path); await expect(page.getByRole('status')).toHaveText('Ready');
  const editor = page.getByRole('textbox', { name: 'Suggestion editor', exact: true });
  const suggestions = editor.getByRole('region', { name: 'Suggested replacement', exact: true });
  await suggestions.focus(); await page.getByRole('button', { name: 'Edit selected suggestion', exact: true }).click();
  await page.getByLabel('Replacement source', { exact: true }).fill('return 42;\n\n');
  await page.getByRole('button', { name: 'Apply source', exact: true }).click();
  await expect(suggestions.locator('code')).toHaveText('return 42;\n\n', { useInnerText: false });
  await suggestions.focus(); await page.getByRole('button', { name: 'Edit selected suggestion', exact: true }).click();
  await page.getByRole('button', { name: 'Load file lines', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('File lines loaded');
  await expect(page.locator('#original')).toHaveText('1: first\n2: original A\n3: original B\n4: last');
  await page.getByLabel('First file line', { exact: true }).fill('1'); await page.getByLabel('Last file line', { exact: true }).fill('4');
  await page.getByRole('button', { name: 'Apply range', exact: true }).click(); await expect(page.getByRole('status')).toHaveText('Range updated');
  await expect(suggestions).toHaveAttribute('data-fountain-gitlab-suggestion', '-2+1');
  await expect.poll(() => suggestions.locator('code').textContent()).toBe('return 42;\n\n');
  await page.getByRole('button', { name: 'Export Markdown', exact: true }).click();
  const changed = await page.getByLabel('Saved Markdown', { exact: true }).inputValue(); expect(changed).toContain('```suggestion:-2+1\nreturn 42;\n\n```');
  await page.screenshot({ path: resolve(output, 'range.png'), fullPage: true });
  await page.getByRole('button', { name: 'Undo', exact: true }).click(); await expect(suggestions).toHaveAttribute('data-fountain-gitlab-suggestion', '');
  await page.getByRole('button', { name: 'Undo', exact: true }).click(); await expect.poll(() => suggestions.locator('code').textContent()).toBe('return true;\n');
  await suggestions.focus(); await page.keyboard.press('Control+Enter');
  await page.keyboard.type('Review notes.'); await expect(editor.locator('p')).toHaveText('Review notes.');
  await page.getByRole('button', { name: 'Insert suggestion', exact: true }).click(); await expect(suggestions).toHaveCount(2);
  await expect(suggestions.nth(1)).toHaveAttribute('data-fountain-gitlab-suggestion', '-1+0');
  await expect.poll(() => suggestions.nth(1).locator('code').textContent()).toBe('original A\noriginal B\n');
  await suggestions.nth(1).focus(); await page.getByRole('button', { name: 'Edit selected suggestion', exact: true }).click();
  await page.getByLabel('Replacement source', { exact: true }).fill('forbidden');
  await page.getByRole('button', { name: 'Revoke suggestion permission', exact: true }).click();
  await page.getByRole('button', { name: 'Apply source', exact: true }).click(); await expect(page.getByRole('status')).toHaveText('GITLAB_SUGGESTION_UNAVAILABLE');
  await expect.poll(() => suggestions.nth(1).locator('code').textContent()).toBe('original A\noriginal B\n');
  await page.getByRole('button', { name: 'Export Markdown', exact: true }).click();
  await writeFile(resolve(output, 'observations.json'), JSON.stringify({ sourceUpdated: true, rangeExpandedWithFile: true, sourceRetainedOnRangeChange: true,
    undoSeparate: true, insertion: true, revokedPermissionRefused: true, changed, saved: await page.getByLabel('Saved Markdown', { exact: true }).inputValue(), errors }, null, 2) + '\n');
  expect(errors).toEqual([]);
});
